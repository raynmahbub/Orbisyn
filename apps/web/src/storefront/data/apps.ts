import type { BridgeId, Category, Platform, StoreApp, Verification } from '../types.js';

/**
 * Curated preview catalog.
 *
 * The references are real upstream project pages so “Verify live source” can
 * call the provider engine. Versions, sizes, screenshots and editor copy are
 * clearly marked as preview metadata; they are never presented as a substitute
 * for a live upstream release check.
 */

interface AppSeed {
  readonly id: string;
  readonly name: string;
  readonly developer: string;
  readonly tagline: string;
  readonly description: string;
  readonly category: Category;
  readonly platforms: readonly Platform[];
  readonly sourceIds: readonly BridgeId[];
  readonly reference: string;
  readonly sourceUrl: string;
  readonly license: string;
  readonly icon: string;
  readonly color: string;
  readonly colorAlt: string;
  readonly demoVersion: string;
  readonly demoPreviousVersion: string;
  readonly demoSize: string;
  readonly demoUpdated: string;
  readonly openSource?: boolean;
  readonly verification?: Verification;
  readonly featured?: boolean;
  readonly trending?: boolean;
  readonly editorsChoice?: boolean;
  readonly fresh?: boolean;
  readonly updateReady?: boolean;
  readonly liveResolve?: boolean;
  readonly formats?: readonly string[];
  readonly permissions?: readonly string[];
  readonly highlights?: readonly string[];
  readonly checks?: readonly string[];
  readonly releaseNotes?: readonly string[];
  readonly screenshots?: readonly { title: string; body: string }[];
}

function inferFormats(platforms: readonly Platform[]): readonly string[] {
  const formats = new Set<string>();
  for (const platform of platforms) {
    if (platform === 'android') formats.add('APK');
    if (platform === 'windows') formats.add('EXE · MSI · ZIP');
    if (platform === 'macos') formats.add('DMG · PKG');
    if (platform === 'linux') formats.add('AppImage · DEB · RPM');
    if (platform === 'web') formats.add('PWA');
    if (platform === 'ios') formats.add('IPA / TestFlight');
  }
  return [...formats];
}

function defaultScreenshots(name: string, tagline: string): StoreApp['screenshots'] {
  return [
    { title: 'Designed around focus', body: `${name} keeps the primary action one tap away.` },
    { title: 'Your data stays yours', body: 'Source, license and release evidence are visible.' },
    { title: tagline, body: 'A consistent experience across every supported device.' },
  ];
}

function makeApp(seed: AppSeed): StoreApp {
  const openSource = seed.openSource ?? true;
  const verification = seed.verification ?? 'verified';
  return {
    id: seed.id,
    name: seed.name,
    developer: seed.developer,
    tagline: seed.tagline,
    description: seed.description,
    category: seed.category,
    platforms: seed.platforms,
    sourceIds: seed.sourceIds,
    reference: seed.reference,
    sourceUrl: seed.sourceUrl,
    license: seed.license,
    openSource,
    verification,
    icon: seed.icon,
    color: seed.color,
    colorAlt: seed.colorAlt,
    formats: seed.formats ?? inferFormats(seed.platforms),
    permissions:
      seed.permissions ??
      (openSource
        ? ['Upstream source visible', 'User-controlled install', 'No account required']
        : ['Vendor permissions apply', 'Review before install', 'Companion handoff']),
    highlights: seed.highlights ?? [
      'Available through more than one distribution path',
      'Release source is visible before you install',
      'Updates follow the same source as the original package',
    ],
    checks: seed.checks ?? [
      'Canonical source reference declared',
      'License metadata attached',
      'Stable and prerelease channels separated',
      'No invented checksum or download count',
      verification === 'verified' ? 'Maintainer page linked' : 'Community review requested',
    ],
    releaseNotes: seed.releaseNotes ?? [
      'Refined onboarding and first-run experience.',
      'Improved compatibility with current platform releases.',
      'Performance work and smaller incremental updates.',
    ],
    screenshots: seed.screenshots ?? defaultScreenshots(seed.name, seed.tagline),
    featured: seed.featured ?? false,
    trending: seed.trending ?? false,
    editorsChoice: seed.editorsChoice ?? false,
    fresh: seed.fresh ?? false,
    updateReady: seed.updateReady ?? false,
    liveResolve: seed.liveResolve ?? true,
    demoVersion: seed.demoVersion,
    demoPreviousVersion: seed.demoPreviousVersion,
    demoSize: seed.demoSize,
    demoUpdated: seed.demoUpdated,
  };
}

